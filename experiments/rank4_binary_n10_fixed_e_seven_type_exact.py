#!/usr/bin/env python3
"""Exact seven-type fixed-e audit for the binary n=10 t=0 class.

Reuses the exact two-deletion-robust binary n=10 census:
  * 28,476 multiplicity patterns;
  * 16 GL(4,2) orbits;
  * 160 pointed orbit representatives.

The omitted element is held fixed.  The move set is the seven local
four-position permutation types isolated by the historical n=18
minimization audit:

  adjacent transpositions:
    (1,0,2,3), (0,2,1,3), (0,1,3,2)

  nonadjacent patterns:
    (2,3,0,1), (2,3,1,0), (3,1,2,0), (0,3,2,1)

For every pointed orbit representative, enumerate all deletion CBOs modulo
rotation, build the graph generated by CBO-preserving moves from this family,
check every component contains an insertion-successful CBO, and compute the
exact maximum distance to success.

Finite exact computation; not Lean certification.
"""

from collections import deque
import json

import rank4_binary_n10_nonsimple_exact as base

MOVE_TYPES = (
    (1,0,2,3),
    (0,2,1,3),
    (0,1,3,2),
    (2,3,0,1),
    (2,3,1,0),
    (3,1,2,0),
    (0,3,2,1),
)


def canonical(order):
    order = tuple(order)
    i = order.index(min(order))
    return order[i:] + order[:i]


def successful(columns, omitted, order):
    return base.successful(columns, (omitted, order))


def audit_fixed_e(columns, omitted):
    orders = set(base.deletion_cbos(columns, omitted))
    good = {o: successful(columns, omitted, o) for o in orders}
    adj = {o: set() for o in orders}

    for order in orders:
        m = len(order)
        for start in range(m):
            inds = [(start + j) % m for j in range(4)]
            old = [order[i] for i in inds]
            for patt in MOVE_TYPES:
                a = list(order)
                for dst, src in enumerate(patt):
                    a[inds[dst]] = old[src]
                t = canonical(a)
                if t in orders and t != order:
                    adj[order].add(t)
                    adj[t].add(order)

    unseen = set(orders)
    maxdist = 0
    components = 0
    while unseen:
        root = unseen.pop()
        comp = {root}
        stack = [root]
        while stack:
            u = stack.pop()
            for v in adj[u]:
                if v not in comp:
                    comp.add(v)
                    unseen.discard(v)
                    stack.append(v)
        components += 1

        seeds = [x for x in comp if good[x]]
        if not seeds:
            return {
                "deletion_cbos": len(orders),
                "components": components,
                "closed_all_bad_components": 1,
                "maximum_distance_to_success": None,
            }

        dist = {x: 0 for x in seeds}
        q = deque(seeds)
        while q:
            u = q.popleft()
            for v in adj[u]:
                if v in comp and v not in dist:
                    dist[v] = dist[u] + 1
                    q.append(v)
        assert len(dist) == len(comp)
        maxdist = max(maxdist, max(dist.values()))

    return {
        "deletion_cbos": len(orders),
        "components": components,
        "closed_all_bad_components": 0,
        "maximum_distance_to_success": maxdist,
    }


def main():
    patterns, _ = base.qualifying_patterns()
    assert len(patterns) == 28476
    reps = base.orbit_representatives(patterns)
    assert len(reps) == 16
    assert sum(size for _, size in reps) == 28476

    orbit_maxima = []
    total_closed_bad = 0
    global_maxdist = 0

    for oi, (counts, orbit_size) in enumerate(reps):
        columns = base.labelled_columns(counts)
        pointed = [audit_fixed_e(columns, e) for e in range(10)]
        closed = sum(x["closed_all_bad_components"] for x in pointed)
        omax = max(x["maximum_distance_to_success"] for x in pointed)
        total_closed_bad += closed
        global_maxdist = max(global_maxdist, omax)
        orbit_maxima.append({
            "orbit_index": oi,
            "orbit_size": orbit_size,
            "maximum_fixed_e_repair_distance": omax,
            "closed_all_bad_fixed_e_components": closed,
        })

    assert total_closed_bad == 0
    assert global_maxdist == 4

    print(json.dumps({
        "scope": (
            "complete binary represented n=10 class satisfying exact "
            "two-deletion flat caps (2,4,6)"
        ),
        "multiplicity_patterns": 28476,
        "gl4_2_orbits": 16,
        "pointed_orbit_representatives": 160,
        "move_types": [list(p) for p in MOVE_TYPES],
        "closed_all_bad_fixed_e_components": total_closed_bad,
        "maximum_fixed_e_distance_to_success": global_maxdist,
        "orbit_summaries": orbit_maxima,
        "interpretation": (
            "The seven-type move family isolated from the historical n=18 "
            "stress is already sufficient throughout the complete exact "
            "binary n=10 two-deletion-robust class. Its worst exact fixed-e "
            "repair distance is four, equal to the arbitrary-S4 audit."
        ),
        "claim_level": "exact finite computation; not Lean certification",
    }, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
