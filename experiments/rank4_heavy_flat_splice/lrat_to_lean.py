"""Write a Lean probe module that kernel-checks an LRAT certificate with Mathlib's `lrat_proof`.

Reads certs/NAME.cnf and certs/NAME.lrat (from cert_measure.py and lrat_emit.py) and writes
probes/Probe/<Module>.lean at the repository root.  The module states only the propositional
unsatisfiability of the CNF; the encoding-soundness link to matroids is not part of the probe.

Usage: python lrat_to_lean.py NAME Module   (e.g. python lrat_to_lean.py kum6 Kum6)
"""
import os, sys
from cert_measure import OUT

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))


def one_line(path, skip_header=False):
    toks = []
    with open(path) as f:
        for line in f:
            if skip_header and line.startswith(("p", "c")):
                continue
            toks.extend(line.split())
    return " ".join(toks)


def write(name, module):
    cnf = os.path.join(OUT, f"{name}.cnf")
    with open(cnf) as f:
        header = f.readline().split()
    assert header[:2] == ["p", "cnf"]
    body = one_line(cnf, skip_header=True)
    lrat = one_line(os.path.join(OUT, f"{name}.lrat"))
    thm = f"probe_{name}_unsat"
    text = f"""import Mathlib.Tactic.Sat.FromLRAT

/-!
Palomar probe: kernel-check the LRAT certificate for the SAT claim `{name}` with Mathlib's
`lrat_proof`, which uses the Lean kernel as the LRAT checker and needs no extra axioms.

Generated by `experiments/rank4_heavy_flat_splice/lrat_to_lean.py`.  Only the propositional
unsatisfiability of the CNF is stated here; the link to matroids is not part of this probe.
-/

set_option maxHeartbeats 0
set_option maxRecDepth 1000000
set_option profiler true

lrat_proof {thm}
  "p cnf {header[2]} {header[3]} {body}"
  "{lrat}"

#print axioms {thm}
"""
    out_dir = os.path.join(ROOT, "probes", "Probe")
    os.makedirs(out_dir, exist_ok=True)
    out = os.path.join(out_dir, f"{module}.lean")
    with open(out, "w", newline="\n") as f:
        f.write(text)
    print(out, os.path.getsize(out), "bytes")


if __name__ == "__main__":
    write(sys.argv[1], sys.argv[2])
